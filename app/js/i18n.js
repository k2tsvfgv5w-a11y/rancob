export function createT(getLang) {
  return function t(key, params) {
    const lang = getLang();
    let s = STRINGS[lang]?.[key] ?? STRINGS.id[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
