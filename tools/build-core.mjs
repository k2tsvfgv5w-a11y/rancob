#!/usr/bin/env node
// Compiles the Dart facade in core/ (which wraps the app's agri_core package)
// into app/core.js, so the web app runs the exact same statistics as Android.
//
//   node tools/build-core.mjs          compile app/core.js + app/core-version.json
//   node tools/build-core.mjs --check  exit 1 when agri_core or the facade changed
//                                      since app/core.js was last built
//
// RANCOB_APP (default ~/Projects/agri-research-app) points at the app repo.

import { readFileSync, writeFileSync, readdirSync, rmSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { homedir } from 'node:os';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const app = process.env.RANCOB_APP ?? join(homedir(), 'Projects/agri-research-app');
const coreSrc = join(app, 'packages/agri_core');
const check = process.argv.includes('--check');

function dartFiles(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((e) => {
      const p = join(dir, e.name);
      return e.isDirectory() ? dartFiles(p) : e.name.endsWith('.dart') ? [p] : [];
    })
    .sort();
}

// Fingerprint of everything that influences the compiled output.
function fingerprint() {
  const h = createHash('sha256');
  for (const root of [join(coreSrc, 'lib'), join(site, 'core/lib')]) {
    for (const f of dartFiles(root)) {
      h.update(relative(root, f) + '\0');
      h.update(readFileSync(f));
    }
  }
  h.update(readFileSync(join(coreSrc, 'pubspec.yaml')));
  return h.digest('hex');
}

const versionPath = join(site, 'app/core-version.json');
const sha = fingerprint();

if (check) {
  let built = {};
  try {
    built = JSON.parse(readFileSync(versionPath, 'utf8'));
  } catch {}
  if (built.sha256 !== sha) {
    console.error('app/core.js is out of date with agri_core. Run: node tools/build-core.mjs');
    process.exit(1);
  }
  console.log(`app/core.js matches agri_core (${sha.slice(0, 12)}).`);
  process.exit(0);
}

const run = (cmd, args, cwd) => execFileSync(cmd, args, { cwd, stdio: 'inherit' });
writeFileSync(
  join(site, 'core/pubspec_overrides.yaml'),
  `dependency_overrides:\n  agri_core:\n    path: ${coreSrc}\n`,
);
run('dart', ['pub', 'get'], join(site, 'core'));
const out = join(site, 'app/core.js');
run('dart', ['compile', 'js', '-O4', '--no-source-maps', '-o', out, join(site, 'core/lib/main.dart')], site);
rmSync(out + '.deps', { force: true });

let appCommit = 'unknown';
try {
  appCommit = execFileSync('git', ['-C', app, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
} catch {}
writeFileSync(
  versionPath,
  JSON.stringify({ note: 'Generated by tools/build-core.mjs', sha256: sha, appCommit, bytes: statSync(out).size }, null, 2) + '\n',
);
console.log(`Built app/core.js (${statSync(out).size} bytes) from app @ ${appCommit}`);
